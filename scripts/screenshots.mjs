import { chromium } from '@playwright/test';
import fs from 'node:fs';
fs.mkdirSync('docs/screenshots', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--enable-webgl', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
page.on('pageerror', error => console.error('PAGE ERROR:', error.message));
await page.goto('http://127.0.0.1:3000/os/');
await page.waitForTimeout(1500);
await page.screenshot({ path: 'docs/screenshots/desktop.png' });
await page.getByRole('button', { name: 'Open About me', exact: true }).click();
await page.waitForTimeout(350);
await page.screenshot({ path: 'docs/screenshots/about.png' });
await page.goto('http://127.0.0.1:3000/');
await page.waitForTimeout(6000);
await page.screenshot({ path: 'docs/screenshots/room.png' });
await page.setViewportSize({ width: 390, height: 844 });
await page.goto('http://127.0.0.1:3000/os/?app=about');
await page.waitForTimeout(1500);
await page.screenshot({ path: 'docs/screenshots/mobile.png' });
await browser.close();
